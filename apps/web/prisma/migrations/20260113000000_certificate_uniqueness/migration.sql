-- One certificate per learner per training, ever.
--
-- issueCertificate checked for an existing valid certificate with findFirst and then
-- inserted. Nothing sat behind that check at the database level, so two issuances racing
-- -- which the "Issue all eligible" button, which accepts up to 500 users in one request,
-- turned from theoretical into likely -- both saw no existing row and both inserted. The
-- result was two valid certificates for one learner, with two different numbers, both
-- publicly verifiable and indistinguishable from outside.
--
-- RUN THIS BEFORE DEPLOYING:
--
--   SELECT "trainingId", "userId", COUNT(*)
--   FROM "Certificate"
--   GROUP BY "trainingId", "userId"
--   HAVING COUNT(*) > 1;
--
-- If that returns rows, this constraint will fail to apply and the deploy will error
-- rather than silently do the wrong thing. Every duplicate is a real, separately issued,
-- publicly verifiable credential. Do not drop rows automatically: decide per case which
-- to keep, revoke the rest, and notify the holders. Deleting a certificate is worse than
-- revoking it, because the number stops resolving at all and the holder cannot see why.
--
-- Deliberately not a partial index scoped to status = 'valid'. A revoked certificate
-- stays on its row, so a partial index would let a brand new credential be issued to
-- someone whose certificate was revoked for fraud. Restoring goes through
-- restoreCertificate() instead, which is explicit and audited.
ALTER TABLE "Certificate"
  ADD CONSTRAINT "Certificate_trainingId_userId_key" UNIQUE ("trainingId", "userId");